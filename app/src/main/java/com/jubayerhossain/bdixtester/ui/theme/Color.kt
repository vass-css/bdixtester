object BdixThemeRegistry {
  fun specFor(
    preset: AppThemePreset,
    isDark: Boolean,
  ): BdixThemeSpec =
    when (preset) {
      AppThemePreset.MIDNIGHT_INDIGO ->
        if (isDark) {
          BdixThemeSpec(preset, true, MidnightIndigoDarkColorScheme, MidnightIndigoDarkSemantic)
        } else {
          BdixThemeSpec(preset, false, MidnightIndigoLightColorScheme, MidnightIndigoLightSemantic)
        }

      AppThemePreset.GRAPHITE_AMBER ->
        if (isDark) {
          BdixThemeSpec(preset, true, GraphiteAmberDarkColorScheme, GraphiteAmberDarkSemantic)
        } else {
          BdixThemeSpec(preset, false, GraphiteAmberLightColorScheme, GraphiteAmberLightSemantic)
        }

      AppThemePreset.DEEP_EMERALD ->
        if (isDark) {
          BdixThemeSpec(preset, true, DeepEmeraldDarkColorScheme, DeepEmeraldDarkSemantic)
        } else {
          BdixThemeSpec(preset, false, DeepEmeraldLightColorScheme, DeepEmeraldLightSemantic)
        }

      AppThemePreset.WARM_PREMIUM ->
        if (isDark) {
          BdixThemeSpec(preset, true, WarmPremiumDarkColorScheme, WarmPremiumDarkSemantic)
        } else {
          BdixThemeSpec(preset, false, WarmPremiumLightColorScheme, WarmPremiumLightSemantic)
        }
    }

  val allEightSpecs: List<BdixThemeSpec> =
    AppThemePreset.entries.flatMap { preset ->
      listOf(specFor(preset, isDark = false), specFor(preset, isDark = true))
    }
}

